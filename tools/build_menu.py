#!/usr/bin/env python3
"""Rebuild the menu grid and the menu structured data in ../menu.html from menu.json.

Usage:  python3 tools/build_menu.py
Edit tools/menu.json (names, prices, descriptions, thumbnails), run this, then run
tools/build_pdf.py if you also want the PDF menu refreshed.
"""
import json, re, html
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / 'tools' / 'menu.json').read_text(encoding='utf-8'))
esc = lambda s: html.escape(s, quote=False)

def item_html(it):
    kind = 'is-photo' if '/thumbs/' in (it.get('thumb') or '') else 'is-icon'
    badge = ' <span class="diet-badge" title="Vegetarian">V<span class="sr-only"> (vegetarian)</span></span>' if it.get('veg') else ''
    desc = f'\n              <p>{esc(it["desc"])}</p>' if it.get('desc') else ''
    return f'''
          <div class="menu-item">
            <img class="menu-thumb {kind}" src="{it['thumb']}" alt="" width="64" height="64" loading="lazy" decoding="async" />
            <div class="menu-item-text">
              <h3>{esc(it['name'])}{badge}</h3>{desc}
            </div>
            <span class="price">{esc(it['price'])}</span>
          </div>'''

def cat_html(c):
    note = f'\n          <p class="menu-note">{esc(c["note"])}</p>' if c.get('note') else ''
    return f'''
        <section class="page-card menu-category">
          <p class="eyebrow">{esc(c['eyebrow'])}</p>
          <h2>{esc(c['title'])}</h2>{note}{''.join(item_html(i) for i in c['items'])}
        </section>'''

def prices(s):
    return re.findall(r'£\s*(\d+(?:\.\d{2})?)', s)

def menu_ld():
    sections = []
    for c in data['categories']:
        items = []
        for it in c['items']:
            p = prices(it['price'])
            offers = [{'@type': 'Offer', 'price': x, 'priceCurrency': 'GBP'} for x in p]
            d = {'@type': 'MenuItem', 'name': it['name']}
            if it.get('desc'): d['description'] = it['desc']
            if it.get('veg'): d['suitableForDiet'] = 'https://schema.org/VegetarianDiet'
            d['offers'] = offers[0] if len(offers) == 1 else offers
            items.append(d)
        sections.append({'@type': 'MenuSection', 'name': c['title'], 'hasMenuItem': items})
    f = data['feature']
    sections.insert(0, {'@type': 'MenuSection', 'name': 'Sunday special', 'hasMenuItem': [{
        '@type': 'MenuItem', 'name': f['title'], 'description': f['text'],
        'offers': {'@type': 'Offer', 'price': prices(f['price'])[0], 'priceCurrency': 'GBP'}}]})
    return {'@context': 'https://schema.org', '@type': 'Menu', 'name': data['business']['name'] + ' menu',
            'inLanguage': 'en-GB', 'url': data['business']['site'] + 'menu.html', 'hasMenuSection': sections}

page = ROOT / 'menu.html'
h = page.read_text(encoding='utf-8')
grid = '<!-- MENU:START (generated by tools/build_menu.py - edit tools/menu.json instead) -->\n      <div class="menu-grid">' + ''.join(cat_html(c) for c in data['categories']) + '\n      </div>\n      <!-- MENU:END -->'
if '<!-- MENU:START' in h:
    h = re.sub(r'<!-- MENU:START.*?<!-- MENU:END -->', lambda m: grid, h, flags=re.S)
else:
    h = re.sub(r'<div class="menu-grid">.*?\n      </div>', lambda m: grid, h, count=1, flags=re.S)
ld = '<!-- MENU-LD:START -->\n    <script type="application/ld+json">\n' + json.dumps(menu_ld(), indent=2, ensure_ascii=False) + '\n    </script>\n    <!-- MENU-LD:END -->'
if '<!-- MENU-LD:START' in h:
    h = re.sub(r'<!-- MENU-LD:START.*?<!-- MENU-LD:END -->', lambda m: ld, h, flags=re.S)
else:
    h = h.replace('</head>', '    ' + ld + '\n  </head>', 1)
page.write_text(h, encoding='utf-8')
print('menu.html rebuilt:', sum(len(c['items']) for c in data['categories']), 'items')
